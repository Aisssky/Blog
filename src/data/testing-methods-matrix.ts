/** 原文里的 ** 强调还原成 <strong>；\< \> 等导出转义还原成实体 */
export function rich(s: string): string {
  let out = s
    .replace(/\\</g, '&lt;')
    .replace(/\\>/g, '&gt;')
    .replace(/\\([_*\[\]()#+\-.!])/g, '$1');
  let bold = false;
  out = out.replace(/\*\*/g, () => {
    bold = !bold;
    return bold ? '<strong>' : '</strong>';
  });
  return out.replace(/\n/g, '<br>');
}

